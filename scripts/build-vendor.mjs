// Builds extension/vendor/ (the extension itself has no build step):
// - transformers.min.js + ort/, Transformers.js and the ONNX Runtime
//   WebAssembly files it loads, copied so nothing is fetched from a CDN.
// - fonts/geist.woff2, the UI typeface (Geist, SIL OFL 1.1), for the settings
//   page and popup, and geist-font.js, the same bytes for the content script:
//   LinkedIn's page can only load extension files that are web-accessible,
//   and LinkedIn probes those to detect extensions.
// Re-run with `npm run vendor` after bumping a package.
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const vendor = path.join(root, 'extension/vendor');

const tdist = path.join(root, 'node_modules/@huggingface/transformers/dist');
fs.copyFileSync(path.join(tdist, 'transformers.min.js'), path.join(vendor, 'transformers.min.js'));
// The bundled ONNX Runtime loads its WASM backend from env.backends.onnx.wasm.wasmPaths.
const ortOut = path.join(vendor, 'ort');
fs.rmSync(ortOut, { recursive: true, force: true });
fs.mkdirSync(ortOut, { recursive: true });
const ortDist = path.join(root, 'node_modules/onnxruntime-web/dist');
// CPU (WASM) backend only; the WebGPU build isn't needed for a 33M-param encoder.
for (const f of ['ort-wasm-simd-threaded.asyncify.mjs', 'ort-wasm-simd-threaded.asyncify.wasm']) {
  const src = fs.existsSync(path.join(tdist, f)) ? path.join(tdist, f) : path.join(ortDist, f);
  fs.copyFileSync(src, path.join(ortOut, f));
}
console.log('wrote extension/vendor/transformers.min.js and extension/vendor/ort/');

const fontSrc = path.join(root, 'node_modules/@fontsource-variable/geist');
const fontOut = path.join(vendor, 'fonts');
fs.mkdirSync(fontOut, { recursive: true });
// Latin, every weight (variable). Other scripts fall back to the system font.
const font = fs.readFileSync(path.join(fontSrc, 'files/geist-latin-wght-normal.woff2'));
fs.writeFileSync(path.join(fontOut, 'geist.woff2'), font);
fs.copyFileSync(path.join(fontSrc, 'LICENSE'), path.join(fontOut, 'OFL.txt'));
fs.writeFileSync(
  path.join(vendor, 'geist-font.js'),
  '// Generated by scripts/build-vendor.mjs: Geist (SIL OFL 1.1, see fonts/OFL.txt) as base64,\n' +
    '// for the content script. Registered by content/panel.js.\n' +
    '(globalThis.control = globalThis.control || {}).fontData =\n' +
    `  '${font.toString('base64')}';\n`,
);
console.log('wrote extension/vendor/fonts/ and extension/vendor/geist-font.js');
